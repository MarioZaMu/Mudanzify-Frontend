// Copies the IPC contract from mudanzify-backend (its single source of truth)
// into src/bridge/contract.ts. Run it whenever the backend contract changes.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const backendDir = path.resolve(root, process.env.BACKEND_DIR ?? '../mudanzify-backend');
const source = path.join(backendDir, 'src', 'shared', 'contract.ts');
const target = path.join(root, 'src', 'bridge', 'contract.ts');

if (!existsSync(source)) {
  console.error(`[sync:contract] Contract not found at ${source}.`);
  process.exit(1);
}

const header =
  '// AUTO-GENERATED by `npm run sync:contract` from mudanzify-backend/src/shared/contract.ts.\n' +
  '// Do not edit by hand: change the backend contract and sync again.\n\n';

writeFileSync(target, header + readFileSync(source, 'utf8'));
console.log(`[sync:contract] ${source} -> ${target}`);
